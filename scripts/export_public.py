def norm(t: str) -> str:
    return re.sub(r"\s+", " ", t.lower()).strip()


def windows(texts, w: int) -> set[str]:
    out = set()
    for t in texts:
        t = norm(t)
        out.update(x for i in range(0, len(t) - w + 1, w) if len(set(x := t[i:i + w])) >= 12)   # skip "-----"
    return out


def apply(rule, text: str, f: str) -> str:
    """A scrub rule: ["old", "new"] (exact) · {"regex": ..., "new": ...} · {"between": [start, end], "new": ...}.
    A rule that no longer matches stops the export, so a doc edit can't silently re-expose something."""
    if isinstance(rule, list):
        old, new = rule
        ok, out = old in text, text.replace(old, new)
    elif "regex" in rule:
        out, n = re.subn(rule["regex"], rule["new"], text)
        ok = n > 0
    else:
        start, end = rule["between"]
        i = text.find(start)
        j = text.find(end, i + 1) if i >= 0 else -1
        ok, out = j > i >= 0, text[:i] + rule["new"] + text[j:]
    if not ok:
        sys.exit(f"scrub rule no longer matches in {f}: {str(rule)[:80]} (update export_scrub.local.json)")
    return out


def build(dest: Path, holder: str) -> list[Path]:
    dest.mkdir(parents=True, exist_ok=True)
    for p in dest.iterdir():                                       # rebuild, but keep the export's own git history
        if p.name != ".git":
            shutil.rmtree(p) if p.is_dir() else p.unlink()
    files = [f for f in subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True,
                                       check=True).stdout.splitlines() if not EXCLUDE.match(f)]
    scrub = json.loads(SCRUB_FILE.read_text()) if SCRUB_FILE.exists() else {}
    for f in files:
        src, out = ROOT / f, dest / f
        out.parent.mkdir(parents=True, exist_ok=True)
        if f.endswith(".ipynb"):
            nb = json.loads(src.read_text())
            for c in nb["cells"]:
                if c["cell_type"] == "code":
                    c["outputs"], c["execution_count"] = [], None
            text = json.dumps(nb, indent=1, ensure_ascii=False) + "\n"
        elif src.suffix in TEXT_EXT:
            text = src.read_text()
        else:
            shutil.copy2(src, out)
            continue
        for rule in scrub.get(f, []):
            text = apply(rule, text, f)
        out.write_text(text)
    (dest / "testset").mkdir(exist_ok=True)
    (dest / "testset" / "README.md").write_text(TESTSET_README)
    (dest / "LICENSE").write_text(LICENSE.format(holder=holder))
    return [p for p in dest.rglob("*") if p.is_file() and ".git" not in p.relative_to(dest).parts]


def private_terms(manifest: pd.DataFrame) -> set[str]:
    terms = {t.strip().lower() for t in TERMS_FILE.read_text().splitlines() if t.strip()} if TERMS_FILE.exists() else set()
    for path in manifest.loc[manifest.reason.eq("another student's submission"), "path"]:
        terms.update(w.lower() for w in re.findall(r"[A-Z][a-z]{2,}", Path(path).stem))   # classmates' names
    return terms


PHRASE_ALLOW = {"and the", "one page", "old exams", "cheat sheets", "cheat sheet", "mock exam", "problem set",
                "summary for", "lecture slides", "create copies", "feistel and", "exam solutions", "template for",
                "midterm mock", "pitch deck", "table creation", "for dummies", "set solution", "key crypto"}


def corpus_phrases(manifest: pd.DataFrame) -> set[str]:
    """Two-word phrases from corpus file/folder names (catches lecture titles inside longer names)."""
    courses = {c.lower() for c in manifest.course.unique()}
    grams = set()
    for path in manifest.path:
        for part in Path(path).parts[2:]:
            w = [x for x in re.split(r"[^a-z]+", Path(part).stem.lower()) if len(x) >= 3]
            grams |= {f"{a} {b}" for a, b in zip(w, w[1:])}
    return {g for g in grams if g not in PHRASE_ALLOW and not any(g in c for c in courses)}


def corpus_names(manifest: pd.DataFrame) -> set[str]:
    names = set()
    for path in manifest.path:
        parts = Path(path).parts
        for part in parts[2:]:                                     # skip "Semester X" and the course folder
            stem = Path(part).stem.lower().strip()
            if len(stem) >= 5 and stem not in GENERIC and not stem.isdigit():
                names.add(stem)
    return names


def scan(files: list[Path], dest: Path) -> list[str]:
    manifest = pd.read_csv(ROOT / "data" / "manifest.csv")
    chunks = pd.read_parquet(ROOT / "data" / "chunks.parquet", columns=["text"]).text
    testset = [p.read_text() for p in (ROOT / "testset").glob("*") if p.is_file()]
    corpus_w, test_w = windows(chunks, CORPUS_W), windows(testset, TESTSET_W)
    terms, names, phrases = private_terms(manifest), corpus_names(manifest), corpus_phrases(manifest)
    term_re = re.compile(r"(?<![a-z])(" + "|".join(map(re.escape, sorted(terms))) + r")(?![a-z])") if terms else None
    pats = {"email": re.compile(r"[\w.+-]+@[\w-]+\.[a-z]{2,}", re.I),
            "local path": re.compile("|".join(["/" + "Users/", "/private" + "/tmp", r"C:\\" + "Users"])),  # split: not self-matching
            "api key": re.compile(r"sk-ant-[A-Za-z0-9_-]{8,}")}
    hits = []
    for p in files:
        rel = p.relative_to(dest)
        try:
            raw = p.read_text()
        except UnicodeDecodeError:
            continue
        low, t = raw.lower(), norm(raw)
        for kind, rx in pats.items():
            hits += [f"{rel}: {kind}: {m.group(0)}" for m in rx.finditer(raw)]
        if term_re:
            hits += [f"{rel}: private term: {m.group(0)}" for m in term_re.finditer(low)]
        hits += [f"{rel}: corpus name: {n}" for n in names if re.search(r"(?<![a-z0-9])" + re.escape(n) + r"(?![a-z0-9])", low)]
        words = " " + re.sub(r"[^a-z]+", " ", low) + " "
        hits += [f"{rel}: corpus phrase: {g}" for g in phrases if f" {g} " in words]
        for w, pool, kind in [(CORPUS_W, corpus_w, "corpus passage"), (TESTSET_W, test_w, "test-set passage")]:
            found = {t[i:i + w] for i in range(len(t) - w + 1) if t[i:i + w] in pool}
            hits += [f"{rel}: {kind}: …{x}…" for x in sorted(found)[:3]]
    return hits


if __name__ == "__main__":
    dest = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else (ROOT.parent / "ragtraining")
    if dest == ROOT or ROOT in dest.parents:
        sys.exit("export folder must be outside this repo")
    holder = sys.argv[2] if len(sys.argv) > 2 else "the author"
    files = build(dest, holder)
    hits = scan(files, dest)
    print(f"exported {len(files)} files to {dest}")
    if hits:
        print(f"\nLEAK CHECK FAILED: {len(hits)} hit(s)\n" + "\n".join(sorted(set(hits))))
        sys.exit(1)
    print("leak check: PASS (no emails, private terms, corpus names or copied passages)")
