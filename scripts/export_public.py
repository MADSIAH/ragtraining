"""Build a clean public copy of this repo in a separate folder, then refuse it if anything private leaks.

    .venv/bin/python scripts/export_public.py ../ragtraining           (folder is rebuilt; its .git/ is kept)

What it does:
  1. copies the tracked files, minus EXCLUDE (the test set and personal notes);
  2. applies the exact text replacements in export_scrub.local.json (git-ignored: it holds the strings it removes);
  3. clears every notebook output; adds testset/README.md and LICENSE;
  4. scans every exported file and FAILS (exit 1) on:
     - an email address, an absolute local path or an API-key-like string,
     - a private term (export_private_terms.local.txt, plus classmates' names taken from data/manifest.csv),
     - a corpus file or folder name, or a two-word phrase from one, e.g. a lecture title (course names allowed),
     - any passage of >= 120 characters copied from the corpus chunks, or >= 80 from the test set.
Nothing is pushed anywhere: the output is a plain folder.
"""
