import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
EXCLUDE = re.compile(r"^(testset/|rag_and_vector_embeddings_summary\.md$)")
SCRUB_FILE, TERMS_FILE = ROOT / "export_scrub.local.json", ROOT / "export_private_terms.local.txt"
CORPUS_W, TESTSET_W = 60, 40     # aligned windows: catch any copy of >= 2W-1 chars (119 / 79)
TEXT_EXT = {".py", ".md", ".txt", ".json", ".toml", ".ini", ".ipynb", ".example", ".gitignore", ""}
GENERIC = {"slides", "lecture", "lectures", "exams", "old exams", "solutions", "homework", "notes", "summary",
           "exercises", "readme", "project", "theory", "formulas", "book", "books", "chapter", "midterm", "final",
           "images", "figures", "assignments", "labs", "materials", "resources", "extra", "other", "misc",
           # ordinary words that also happen to be file/folder names in the corpus
           "sources", "slide", "summaries", "header", "design", "zeros", "script", "diagrams", "straight", "report",
           "presentation", "portfolio", "github", "codes", "cheat sheets", "cheat_sheet", "syllabus", "spaces",
           "mock exam", "digits", "esercizi", "create_copies", "assingments", "problem set", "problem sets"}

